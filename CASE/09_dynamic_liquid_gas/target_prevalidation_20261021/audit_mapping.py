#!/usr/bin/env python3
"""SI -> lattice mapping from the model design; no solver execution."""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
DESIGN = HERE.parent / 'mechanism_study_20261021/design.json'

def derive():
    d = json.loads(DESIGN.read_text())
    m = {k: v['value'] for k, v in d['material'].items() if isinstance(v, dict) and 'value' in v}
    dx = d['numerics']['candidate_dx_nm'] * 1e-9
    rl, rg = m['liquid_density_kg_m3'], m['gas_density_kg_m3']
    ml, mg = m['liquid_dynamic_viscosity_Pa_s'], m['gas_dynamic_viscosity_Pa_s']
    nl, ng = ml / rl, mg / rg
    tl = d['numerics']['candidate_tau_liquid']
    dt = (tl - .5) * dx**2 / (3 * nl)
    ps = rl * (dx / dt)**2
    sig = m['liquid_gas_surface_tension_N_m'] * dt**2 / (rl * dx**3)
    tp = d['numerics']['candidate_tau_phase']
    mobility = (tp - .5) / 3
    out = dict(dx_m=dx, dt_s=dt, rho_reference_kg_m3=rl,
               rho_liquid_lattice=1., rho_gas_lattice=rg/rl,
               nu_liquid_m2_s=nl, nu_gas_m2_s=ng,
               tau_liquid=tl, tau_gas=.5+3*ng*dt/dx**2,
               tau_phase=tp, sigma_lattice=sig,
               interface_width_nodes=d['numerics']['candidate_interface_width_nodes'],
               pressure_scale_Pa=ps, velocity_scale_m_s=dx/dt,
               phase_mobility_lattice=mobility,
               phase_mobility_m2_Pa_s=mobility*dx**2/(dt*ps),
               phi_max_for_positive_density=rl/(rl-rg),
               body_force_G1e7_lattice=1e7*dt**2/(rl*dx),
               model_assumptions_not_GHY=True)
    # Independent SI round trips, including the easily confused dynamic viscosity.
    assert abs(out['rho_gas_lattice'] * rl - rg) < 1e-12
    for tau, density, mu in [(tl, rl, ml), (out['tau_gas'], rg, mg)]:
        assert abs(density * (tau-.5)/3 * dx**2/dt / mu - 1) < 1e-12
    assert abs(sig*rl*dx**3/dt**2/m['liquid_gas_surface_tension_N_m']-1) < 1e-12
    assert out['phi_max_for_positive_density'] < 1.05
    return out

def main():
    out = derive()
    out['design_sha256'] = hashlib.sha256(DESIGN.read_bytes()).hexdigest()
    (HERE/'mapping.json').write_text(json.dumps(out, indent=2)+'\n')
    pairs = {'dxSI':'dx_m','dtSI':'dt_s','rhoRef':'rho_reference_kg_m3',
             'rhoL':'rho_liquid_lattice','rhoG':'rho_gas_lattice',
             'tauL':'tau_liquid','tauG':'tau_gas','tauPhase':'tau_phase',
             'sigma':'sigma_lattice','interfaceWidth':'interface_width_nodes',
             'pressureScale':'pressure_scale_Pa','velocityScale':'velocity_scale_m_s',
             'bodyForce':'body_force_G1e7_lattice'}
    header = '// Generated by audit_mapping.py from model design, NOT measured GHY.\n#pragma once\n'
    header += '\n'.join(f'constexpr double {k} = {out[v]:.17g};' for k,v in pairs.items())+'\n'
    (HERE/'src/target_parameters.h').write_text(header)
    print(json.dumps(out, indent=2))

if __name__ == '__main__':
    main()
