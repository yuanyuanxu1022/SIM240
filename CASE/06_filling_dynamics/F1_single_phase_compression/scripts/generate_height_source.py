#!/usr/bin/env python3
"""Generate one fixed-height F1 single-phase source variant."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


DX_NM = 2.5


def replace_once(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise RuntimeError(f"expected exactly one occurrence of: {old!r}")
    return text.replace(old, new)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--height-nm", type=int, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.height_nm <= 0 or args.height_nm % 5:
        raise SystemExit("height-nm must be a positive multiple of 5 nm")
    cells = args.height_nm / DX_NM
    if not cells.is_integer():
        raise SystemExit("height-nm must be exactly represented at dx=2.5 nm")

    case_root = Path(__file__).resolve().parents[1]
    frozen = case_root / "src" / "f1_single_phase_compression.cpp"
    source = frozen.read_text()

    height_literal = f"{args.height_nm}.0e-9"
    fluid_nodes = int(96 * 96 * cells + 48 * 96 * (100 / DX_NM))
    generated = source
    generated = replace_once(generated, "constexpr T mesaGap = 75.0e-9;", f"constexpr T mesaGap = {height_literal};")
    generated = replace_once(generated, 'p.caseId = "F1-single-phase-P";', f'p.caseId = "F1-single-phase-h{args.height_nm}-P";')
    generated = replace_once(generated, 'p.caseId = "F1-single-phase-T";', f'p.caseId = "F1-single-phase-h{args.height_nm}-T";')
    generated = replace_once(generated, "constexpr long long expectedFluidNodes = 460800;", f"constexpr long long expectedFluidNodes = {fluid_nodes};")
    generated = replace_once(generated, 'SuperVTMwriter3D<T> writer("g2_ex240_" + p.directionName, overlap);', f'SuperVTMwriter3D<T> writer("f1_single_phase_h{args.height_nm}_" + p.directionName, overlap);')
    generated = generated.replace("K0_smooth_h75_m3=", f"K0_smooth_h{args.height_nm}_m3=")

    header = (
        "// Generated by scripts/generate_height_source.py; do not edit.\n"
        f"// template_sha256={hashlib.sha256(source.encode()).hexdigest()}\n"
        f"// mesa_gap_nm={args.height_nm}; expected_fluid_nodes={fluid_nodes}\n\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header + generated)
    print(f"generated={args.output} height_nm={args.height_nm} fluid_nodes={fluid_nodes}")


if __name__ == "__main__":
    main()
