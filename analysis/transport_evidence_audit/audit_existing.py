def diagnostics(path, result, f2=False):
    with path.open(newline="") as fh:
        reader = csv.reader(fh)
        header = next(reader)
        names = header[:16] + ["fill_ratio", "window_rel_std", "window_rel_span",
                              "window_cross_abs_max", "finite"] if f2 else header
        schema_ok = names == header
        rows = []
        for step, line in enumerate(reader):
            frozen.require(len(line) == len(names), f"truncated diagnostic row {path}")
            row = dict(zip(names, map(float, line)))
            frozen.require(all(math.isfinite(v) for v in row.values()), f"nonfinite {path}")
            frozen.require(row["step"] == step and row["finite"] == 1, f"step/finite {path}")
            rows.append(row)
    frozen.require(len(rows) == int(result["steps_completed"]) + 1, f"step coverage {path}")
    peak = max(abs(r["mass_error"]) for r in rows)
    frozen.require(peak < 1e-10 and close(peak, float(result["max_mass_abs_relative"])), f"mass {path}")
    frozen.require(max(r["Mach"] for r in rows) < .05
                   and max(r["max_density_deviation"] for r in rows) <= 1e-6, f"Mach/density {path}")
    tail = rows[-1000:]
    js = [r["J"] for r in tail]
    mean = statistics.mean(js)
    std = statistics.stdev(js) / abs(mean)
    span = (max(js) - min(js)) / abs(mean)
    frozen.require(std <= 1e-6 and span <= 5e-6, f"recomputed window {path}")
    frozen.require(close(rows[-1]["window_rel_std"], float(result["window_main_rel_std"]), 1e-6),
                   f"window column mismatch {path}")
    return {"schema_PASS": schema_ok, "interpretation": "explicit F2 positional mapping" if f2 else "original header",
            "rows": len(rows), "mass_peak": peak, "mass_tail_min": min(r["mass_error"] for r in tail),
            "mass_tail_max": max(r["mass_error"] for r in tail), "window_std_recomputed": std,
            "window_span_recomputed": span}


def height_field(path, height):
    cells = round(height / 2.5)
    expected = {(ix, iz) for ix in range(96) for iz in
                range(cells + 40 if 24 <= ix < 72 else cells)}
    seen = set()
    with path.open(newline="") as fh:
        reader = csv.DictReader(fh)
        frozen.require(reader.fieldnames == HEADER, f"field header {path}")
        for row in reader:
            frozen.require(None not in row, f"extra column {path}")
            values = {k: float(v) for k, v in row.items()}
            frozen.require(all(math.isfinite(v) for v in values.values()), f"nonfinite field {path}")
            raw = (values["x"] / DX - .5, values["z"] / DX - .5)
            point = tuple(round(v) for v in raw)
            frozen.require(all(abs(v-i) < 1e-7 for v,i in zip(raw, point))
                           and point in expected and point not in seen, f"field coverage {path}")
            frozen.require(values["material"] == 1 and values["rho"] > 0, f"field material {path}")
            seen.add(point)
    frozen.require(seen == expected, f"field missing points {path}")
    return len(seen)


def audit_height(path, family):
    register(path)
    v = frozen.parse_kv(path / "result.txt")
    b = frozen.parse_kv(path / "boundary_audit.txt")
    m = frozen.parse_kv(path / "run_manifest.txt")
    height = round(float(v["mesa_gap_m"]) * 1e9)
    direction = "P" if v["direction"] == "parallel" else "T"
    frozen.require(int((path / "exit_code.txt").read_text()) == 0
                   and v["exit_code"] == "0" and v["PASS"] == v["converged"] == "true", f"exit/convergence {path}")
    expected_nodes = 96 * 96 * (height / 2.5 + 20)
    frozen.require(int(v["fluid_nodes"]) == expected_nodes and int(b["material_1"]) == expected_nodes,
                   f"node count {path}")
    for key, expected in (("Lx_m",240e-9),("Ly_m",240e-9),("dx_m",2.5e-9),("tau",1),
                          ("dt_s",1.0416666666666667e-12),("acceleration_m_s2",1e5),
                          ("groove_width_m",120e-9),("groove_depth_m",100e-9),("H_ref_m",(height+50)*1e-9)):
        frozen.require(close(float(v[key]),expected), f"parameter {key}: {path}")
    frozen.require(v["descriptor"] == "D3Q19_FORCE" and v["collision"] == "ForcedBGK"
                   and v["periodicity"] == "x_y", f"model {path}")
    frozen.require(b["geometry_PASS"] == b["q_audit_PASS"] == "true", f"geometry/q {path}")
    for key in ("candidate_links","valid_distance_links","installed_links"):
        frozen.require(int(b[key]) == 130176, f"links {path}")
    for key in ("geometric_fallback_count","missing_fluid_neighbour_fallback_count","unresolved_link_count"):
        frozen.require(int(b[key]) == 0, f"fallback {path}")
    for key in ("q_min","q_max","installed_q_min","installed_q_max"):
        frozen.require(abs(float(b[key])-.5) <= 1e-10, f"q {path}")
    volume = float(v["fluid_volume_m3"])
    nominal = (240e-9)**2 * (height + 50) * 1e-9
    frozen.require(abs(volume-nominal)/nominal <= 1e-10, f"volume {path}")
    for key,limit in (("max_density_deviation",1e-6),("section_relative_difference",1e-5),
                      ("window_main_rel_std",1e-6),("window_main_rel_span",5e-6),("window_cross_abs_max",1e-12)):
        frozen.require(math.isfinite(float(v[key])) and abs(float(v[key]))<=limit, f"gate {key}: {path}")
    frozen.require(v["finite"] == v["material_unchanged"] == "true", f"finite/material {path}")
    diag = diagnostics(path/"diagnostics.csv", v, family == "F2")
    field_rows = height_field(path/"field_slice.csv",height)
    j, k = float(v["J_main_m2_s"]), float(v["Keff_m3"])
    rj = 1e8/j
    rq = 24/statistics.mean(map(float,v["Q_sections_m3_s"].split(",")))
    recorded = float(v["R_eff_Pa_s_per_m3"])
    frozen.require(close(k,1e-3*j/1e8) and close(recorded, rq if family == "F2" else rj), f"normalization {path}")
    provenance = {"recorded_source_hash": False, "source_hash_match": None,
                  "binary_hash_match": None, "generated_source_matches_pinned_family": None}
    if family == "G3-h":
        source = G3/"build/generated"/f"g3_ex240_h{height}.cpp"
        binary = G3/"build"/f"g3_ex240_h{height}"
        register(source); register(binary)
        provenance["binary_hash_match"] = sha(binary) == m["binary_sha256"].split()[0]
        provenance["recorded_source_hash"] = "generated_source_sha256" in m
        provenance["source_hash_match"] = sha(source) == m["generated_source_sha256"] if provenance["recorded_source_hash"] else None
        provenance["source_current_sha256"] = sha(source)
        provenance["generated_source_matches_pinned_family"] = source.read_text() == expected_g3_source(height)
        frozen.require(provenance["generated_source_matches_pinned_family"], f"source whitelist mismatch: {source}")
        provenance["OpenLB_commit_recorded"] = m.get("openlb_commit")
    else:
        binary = F2/"build/f2_liquid_film_compression_dynamic"
        register(binary)
        match = re.search(r"^([a-f0-9]{64})\s+",(path/"run_manifest.txt").read_text(),re.M)
        provenance["binary_hash_match"] = bool(match and sha(binary)==match[1])
    frozen.require(provenance["binary_hash_match"] is True and provenance["source_hash_match"] is not False,
                   f"historical artifact mismatch {path}")
    return {"family":family,"path":str(path),"height_nm":height,"direction":direction,
            "NUMERICAL_GATE":"PASS","geometry_PASS":True,"q_audit_PASS":True,"RESULT_PASS":True,
            "steps":int(v["steps_completed"]),"R_J":rj,"R_Q":rq,"R_recorded":recorded,"K":k,
            "K_over_K0":k/((height*1e-9)**3/12),"R_Q_vs_R_J_relative":abs(rq-rj)/rj,
            "field_rows":field_rows,"diagnostics":diag,"provenance":provenance,
            "final_grid_independent_closure_PASS":False,
            "reuse_status":"CANDIDATE_FIXED_GRID"}


def period_audit():
    results=[]
    for nx,batch in BATCHES.items():
        register(batch)
        frozen.verify_hashes(json.loads((batch/"SOURCE_MANIFEST.json").read_text())["sha256"])
        for tag in frozen.TAGS:
            for d in ("P","T"):
                v,field=frozen.audit_run(batch/"runs"/f"nx{nx}_{d}_{tag}"/"steady",nx)
                results.append(dict(nx=nx,direction=d,force=frozen.TAGS[tag],R=float(v["R_eff_Pa_s_per_m3"]),
                                    K=float(v["Keff_m3"]),steps=int(v["steps_completed"]),field_rows=field["data_rows"],
                                    mass_peak=float(v["max_mass_abs_relative"]),run_PASS=True,batch=batch.name))
        for name in ("workflow_exit_code.txt","postprocess_exit_code.txt"):
            if name=="workflow_exit_code.txt" and nx==2: continue
            frozen.require((batch/name).read_text().strip()=="0",f"batch exit {batch}")
        for row in table(batch/"linearity.csv"):
            frozen.require(float(row["R2"])>=.9999 and float(row["K_max_relative_spread"])<=.01,"linearity")
    expansion=[]
    for previous,current in ((1,2),(2,4),(4,8)):
        for d in ("P","T"):
            prev=baseline_r(d) if previous==1 else next(x["R"] for x in results if x["nx"]==previous and x["direction"]==d and x["force"]==1e5)
            curr=next(x["R"] for x in results if x["nx"]==current and x["direction"]==d and x["force"]==1e5)
            expansion.append(dict(pair=f"{previous}->{current}",direction=d,E=abs(curr-prev)/prev))
    frozen.require(all(math.isfinite(x["E"]) and x["E"] <= .01 for x in expansion
                       if x["pair"] != "1->2"), "consecutive expansion gate failed")
    for d in ("P","T"):
        register(G2_RESULTS/f"G2-{d}"/"steady")
        frozen.audit_run(G2_RESULTS/f"G2-{d}"/"steady",1)
    force=ROOT/"CASE/05_mechanism_analysis/G2_EX240_force_linearity/results/g2_force_linearity_20260917T120627+0800/g2_force_linearity.csv"
    frozen.require(sha(force)=="05e2bf5b999f6fd7a9118e5a9b941047f1a062afa32d2b7841c6c919087af517","Nx=1 force reference hash")
    register(force)
    return results,expansion


